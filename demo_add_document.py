"""Add-document demo (REQ-11.6): ask a question the corpus cannot answer, add the held-out
document through the agent (you approve it in the terminal), and ask again.

    uv run python demo_add_document.py

Run it in a real terminal: add_document is only allowed after you type "y". Results go to
eval/add_document_demo.json (full answers and traces) and eval/add_document_demo.md (readable).
"""
import asyncio
import csv
import json
import sys
from pathlib import Path

import agent

ROOT = Path(__file__).parent
QUESTION_ID = "q31"
DOCUMENT = "corpus/BOE-A-2026-7296.xml"      # Orden PJC/297/2026, arts. 18-19 (2026 RETA contribution brackets)
ADD_REQUEST = f"Añade al índice el documento {DOCUMENT}."   # sent to the agent, so in Spanish like the use case
OUT_JSON = ROOT / "eval" / "add_document_demo.json"
OUT_MD = ROOT / "eval" / "add_document_demo.md"


def question_text(qid: str) -> str:
    with (ROOT / "eval" / "questions.csv").open(encoding="utf-8", newline="") as f:
        return next(row["question"] for row in csv.DictReader(f) if row["id"] == qid)


def quote(text: str) -> list[str]:
    return [f"> {line}" if line else ">" for line in text.splitlines()]


def write_markdown(steps: list[dict], out: Path = OUT_MD, note: str = "") -> None:
    lines = ["# add_document demo", "",
             f"Question {QUESTION_ID} before and after adding `{DOCUMENT}` with `add_document`, "
             "in a single agent session (agent.py). Generated by `demo_add_document.py`. Messages, tool output "
             "and answers are quoted verbatim in Spanish, the language of the use case. The question reads: "
             "*I currently invoice around 600 euros a month. Which contribution bracket applies to me?*"
             + (f" {note}" if note else ""), ""]
    for step in steps:
        r = step["result"]
        lines += [f"## {step['label']}", "", f"**Message:** {r['question']}", "", "**Tools:**", ""]
        for t in r["trace"]:
            if "call" in t:
                lines.append(f"- call `{t['call']}({json.dumps(t['args'], ensure_ascii=False)})`")
            elif t["result"] == "add_document" or t["status"] == "error":
                lines.append(f"- result `{t['result']}` ({t['status']}): {t['text'].strip()}")
            else:
                cites = ", ".join(agent.sources_in(t["text"])) or "(no fragments)"
                lines.append(f"- result `{t['result']}`: {cites}")
        lines += ["", "**Answer:**", "", *quote(r["answer"]), "",
                  f"_Citations: {', '.join(r['citations']) or 'none'} · searches: {r['searches']} · "
                  f"tokens: {r['tokens']['total']} · {r['seconds']} s_", ""]
    out.write_text("\n".join(lines), encoding="utf-8")


async def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    if not sys.stdin.isatty():
        raise SystemExit("Run it in a terminal: add_document needs your approval.")
    question = question_text(QUESTION_ID)
    steps = []
    async with agent.open_agent(agent.ask_in_terminal) as a:
        for label, message in [("1. Before adding the document", question),
                               ("2. Request to add the document", ADD_REQUEST),
                               ("3. After adding the document", question)]:
            print(f"\n=== {label} ===\n{message}\n")
            result = await agent.ask(a, message)
            print(result["answer"])
            steps.append({"label": label, "result": result})
    OUT_JSON.write_text(json.dumps(steps, ensure_ascii=False, indent=2), encoding="utf-8")
    write_markdown(steps)
    print(f"\nSaved to {OUT_JSON.relative_to(ROOT)} and {OUT_MD.relative_to(ROOT)}")


if __name__ == "__main__":
    asyncio.run(main())
