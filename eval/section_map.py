"""
Write eval/section_map.md: every section of every indexed label, with the
number to use in questions.csv (expected_location), its size and opening words.

    uv run python eval/section_map.py
"""

import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import index  # noqa: E402

OUT = ROOT / "eval" / "section_map.md"
PREVIEW_WORDS = 18


def main() -> None:
    lines = [
        "# Section map",
        "",
        "Use `source` as `expected_source` and the **No.** column as `expected_location` in `questions.csv`.",
        "Named sections: `BW` Boxed Warning, `MG` Medication Guide, `PI` Patient Information, `IFU` Instructions for Use.",
        "Generated by `eval/section_map.py` from the same extraction the index uses.",
        "",
    ]
    paths = [index.CORPUS_DIR / f"{name}.xml" for name in index.LABELS]
    paths += [index.HELD_OUT_DIR / f"{name}.xml" for name in index.HELD_OUT]
    for path in paths:
        doc = index.extract_label(path)
        held = " (held out: NOT indexed, added later with add_document)" if path.parent == index.HELD_OUT_DIR else ""
        sections: OrderedDict[tuple[str, str], list[str]] = OrderedDict()
        for block in doc["blocks"]:
            sections.setdefault((block["number"], block["title"]), []).append(block["text"])
        total = sum(len(t.split()) for texts in sections.values() for t in texts)
        lines += [
            f"## {doc['source']}: {doc['brand']} ({doc['generic']}){held}",
            "",
            f"Label version {doc['version_date']}, {total:,} words. Read it at <{doc['url']}>",
            "",
            "| No. | Section | Words | Starts with |",
            "|---|---|---|---|",
        ]
        for (number, title), texts in sections.items():
            words = " ".join(texts).split()
            preview = " ".join(words[:PREVIEW_WORDS]).replace("|", "/")
            lines.append(f"| `{number}` | {title.replace('|', '/')} | {len(words)} | {preview}… |")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
